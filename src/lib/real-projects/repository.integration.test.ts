import { randomUUID } from "node:crypto";
import { Pool } from "pg";
import { afterAll, describe, expect, it } from "vitest";
import type { NegotiationDraft, RealClientRequest, RealProject, ScopeReview } from "@/types/real-project";
import { calculateFinancialImpact } from "./finance";
import { PostgresRealProjectRepository, realProjectScopeHash } from "./repository";
import { buildRealProject, createSourceDocument, groundScopeAnalysis, hashRealInput } from "./source";

const databaseUrl = process.env.SCOPESHIFT_TEST_DATABASE_URL;
const pools: Pool[] = [];
const owned: { scope: string; projectId: string }[] = [];
const projectInput = { name: "Synthetic repository integration", originalFeeCents: 150_000,
  originalEstimatedHours: 20, originalDeadline: "2026-11-20", agreementText: "Build a website. Booking is excluded." };

function repository() {
  const pool = new Pool({ connectionString: databaseUrl, max: 3, connectionTimeoutMillis: 15_000 });
  pools.push(pool);
  return new PostgresRealProjectRepository(pool);
}

async function createOwnedProject(repo: PostgresRealProjectRepository, scope = `real-repository-test-${randomUUID()}`) {
  const project = buildRealProject(projectInput);
  owned.push({ scope, projectId: project.id });
  await repo.createProject(scope, project);
  return { scope, project, projectId: project.id };
}

function requestFor(project: RealProject): RealClientRequest {
  const clientMessage = "Please add consultation booking.";
  return { id: randomUUID(), projectId: project.id, clientMessage, sourceRevision: project.sourceRevision,
    projectSnapshot: project, requestDocument: createSourceDocument(clientMessage, "client_request", "Client request", project.sourceRevision),
    status: "pending", analysis: null, review: null, impact: null, impactHash: null, error: null,
    createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() };
}

function analysisFor(request: RealClientRequest) {
  const doc = request.projectSnapshot.documents[0];
  const requestDoc = request.requestDocument;
  return groundScopeAnalysis({ summary: "Booking is explicitly excluded.", limitations: [], items: [{ title: "Booking",
    requestedWork: request.clientMessage, classification: "excluded", explanation: "The original agreement excludes booking.",
    contractEvidence: [{ documentId: doc.id, passageId: doc.passages[0].id, quote: "Booking is excluded." }],
    requestEvidence: [{ documentId: requestDoc.id, passageId: requestDoc.passages[0].id, quote: request.clientMessage }],
    unknowns: [], clarificationQuestions: [],
  }] }, request.projectSnapshot, requestDoc);
}

async function reviewedRequest(repo: PostgresRealProjectRepository, scope: string, project: RealProject) {
  const record = requestFor(project);
  const args = { scope, projectId: project.id, requestId: record.id };
  const claim = await repo.claimRequest({ ...args, inputHash: hashRealInput(record.clientMessage), record });
  if (!claim.ownerToken) throw new Error("Integration test did not own its synthetic request.");
  const analysis = analysisFor(record);
  await repo.completeAnalysis({ ...args, ownerToken: claim.ownerToken, analysis });
  const review: ScopeReview = { revision: 1, sourceRevision: project.sourceRevision, confirmedAt: new Date().toISOString(),
    items: analysis.items.map((item) => ({ itemId: item.id, classification: item.classification, reason: "Checked in synthetic test." })) };
  await repo.saveReview({ ...args, expectedReviewRevision: 0, review });
  const impact = calculateFinancialImpact(project, { reviewRevision: 1, selectedItemIds: [analysis.items[0].id],
    additionalEstimatedHours: 6, removedScope: [], pricing: { mode: "fixed", feeDeltaCents: 40_000 },
    additionalExpensesCents: 0, deadlineExtensionDays: 2, assumptions: [] }, review);
  const impactHash = hashRealInput(impact);
  const request = await repo.saveImpact({ ...args, expectedReviewRevision: 1, impact, impactHash });
  return { args, request, review, impact, impactHash };
}

function draftFor(request: RealClientRequest, id = randomUUID()): NegotiationDraft {
  if (!request.impactHash || !request.review) throw new Error("Synthetic draft requires reviewed impact.");
  return { id, projectId: request.projectId, requestId: request.id, sourceRevision: request.sourceRevision,
    reviewRevision: request.review.revision, impactHash: request.impactHash, style: "professional", status: "proposed",
    generatedBody: "I propose an additional $400 and two days for booking.", body: "I propose an additional $400 and two days for booking.",
    createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() };
}

afterAll(async () => {
  if (!pools.length) return;
  try {
    // Only IDs generated by this test file are cleaned up, always through their owner scope.
    const repo = new PostgresRealProjectRepository(pools[0]);
    for (const record of owned) {
      if (!record.scope.startsWith("real-repository-test-")) throw new Error("Unsafe synthetic cleanup scope.");
      try { await repo.deleteProject(record.scope, record.projectId); }
      catch (error) { if (!(error && typeof error === "object" && "code" in error && error.code === "NOT_FOUND")) throw error; }
    }
  } finally { await Promise.all(pools.map((pool) => pool.end())); }
}, 60_000);

/** Explicit opt-in only, against a database already migrated through 002.
 * No provider calls, production records, or global deletes are used by this suite.
 */
describe.skipIf(!databaseUrl)("real project Postgres integration", () => {
  it("claims once across connections and restores the exact committed analysis from a new pool", async () => {
    const repos = [repository(), repository(), repository()];
    const { scope, project, projectId } = await createOwnedProject(repos[0]);
    const record = requestFor(project);
    const args = { scope, projectId, requestId: record.id, inputHash: hashRealInput(record.clientMessage), record };
    const claims = await Promise.all(repos.map((repo) => repo.claimRequest(args)));
    expect(claims.filter((claim) => claim.created)).toHaveLength(1);
    expect(claims.filter((claim) => !claim.created).every((claim) => !claim.ownerToken && claim.request.status === "pending")).toBe(true);
    const owner = claims.find((claim) => claim.ownerToken)?.ownerToken;
    if (!owner) throw new Error("No owner for synthetic analysis.");
    const ready = await repos[0].completeAnalysis({ ...args, ownerToken: owner, analysis: analysisFor(record) });
    const fresh = repository();
    await expect(fresh.getRequest(args)).resolves.toEqual(ready);
    await expect(fresh.claimRequest(args)).resolves.toEqual({ created: false, ownerToken: null, request: ready });
    await expect(fresh.claimRequest({ ...args, inputHash: hashRealInput("Different input") })).rejects.toMatchObject({ code: "IDEMPOTENCY_CONFLICT" });
    await expect(fresh.getRequest({ ...args, scope: "different-private-session" })).rejects.toMatchObject({ status: 404, code: "NOT_FOUND" });
    await expect(fresh.getProject("different-private-session", projectId)).rejects.toMatchObject({ status: 404 });
    await expect(fresh.listProjects(scope)).resolves.toEqual([expect.not.objectContaining({ documents: expect.anything() })]);
  }, 60_000);

  it("persists review, deterministic impact and edited drafts, then invalidates stale review mutations", async () => {
    const repo = repository();
    const { scope, project } = await createOwnedProject(repo);
    const { args, request, review, impactHash } = await reviewedRequest(repo, scope, project);
    const draft = draftFor(request);
    const claimArgs = { ...args, draftId: draft.id, inputHash: hashRealInput({ style: draft.style, impactHash }),
      sourceRevision: project.sourceRevision, reviewRevision: review.revision, impactHash, style: draft.style };
    const claims = await Promise.all([repo.claimDraft(claimArgs), repository().claimDraft(claimArgs)]);
    expect(claims.filter((claim) => claim.created)).toHaveLength(1);
    const owner = claims.find((claim) => claim.ownerToken)?.ownerToken;
    if (!owner) throw new Error("No synthetic draft owner.");
    await repo.completeDraft({ ...args, draftId: draft.id, ownerToken: owner, draft });
    await expect(repository().claimDraft(claimArgs)).resolves.toMatchObject({ created: false, status: "complete", draft });
    const edited = await repo.editDraft({ ...args, draftId: draft.id, expectedUpdatedAt: draft.updatedAt, body: "My edited proposal, subject to client approval." });
    expect(edited.generatedBody).toBe(draft.generatedBody);
    expect(edited.body).toBe("My edited proposal, subject to client approval.");
    expect(edited.impactHash).toBe(impactHash);
    await expect(repository().listDrafts(args)).resolves.toEqual([edited]);
    await expect(repository().getDraft({ ...args, draftId: draft.id, scope: "not-this-session" })).rejects.toMatchObject({ status: 404 });
    const secondReview = { ...review, revision: 2, confirmedAt: new Date().toISOString() };
    const changed = await repo.saveReview({ ...args, expectedReviewRevision: 1, review: secondReview });
    expect(changed.impact).toBeNull();
    expect(changed.impactHash).toBeNull();
    await expect(repo.claimDraft(claimArgs)).rejects.toMatchObject({ code: "STALE_REVIEW" });
    await expect(repo.editDraft({ ...args, draftId: draft.id, body: "Attempt to edit obsolete proposal" })).rejects.toMatchObject({ code: "STALE_REVIEW" });
    await expect(repo.saveReview({ ...args, expectedReviewRevision: 1, review: secondReview })).rejects.toMatchObject({ code: "STALE_REVIEW" });
    await expect(repo.getDraft({ ...args, draftId: draft.id })).resolves.toEqual(edited);
  }, 60_000);

  it("keeps immutable source snapshots while blocking completion and calculations after source edits", async () => {
    const repo = repository();
    const { scope, project } = await createOwnedProject(repo);
    const { args, review, impact, request } = await reviewedRequest(repo, scope, project);
    const pending = requestFor(project);
    const pendingArgs = { scope, projectId: project.id, requestId: pending.id };
    const claim = await repo.claimRequest({ ...pendingArgs, inputHash: hashRealInput(pending.clientMessage), record: pending });
    if (!claim.ownerToken) throw new Error("No synthetic analysis owner.");
    const updated = buildRealProject({ ...projectInput, agreementText: "Updated website agreement. Booking is excluded." }, project);
    await repo.updateProject(scope, project.id, 1, updated);
    await expect(repo.completeAnalysis({ ...pendingArgs, ownerToken: claim.ownerToken, analysis: analysisFor(pending) })).rejects.toMatchObject({ code: "STALE_SOURCE" });
    await expect(repo.saveImpact({ ...args, expectedReviewRevision: 1, impact, impactHash: hashRealInput(impact) })).rejects.toMatchObject({ code: "STALE_SOURCE" });
    await expect(repo.saveReview({ ...args, expectedReviewRevision: 1, review: { ...review, revision: 2 } })).rejects.toMatchObject({ code: "STALE_SOURCE" });
    await expect(repo.getRequest(args)).resolves.toEqual(request);
    expect((await repo.listRequests(scope, project.id)).every((row) => row.projectSnapshot.sourceRevision === 1)).toBe(true);
    await expect(repo.updateProject(scope, project.id, 1, updated)).rejects.toMatchObject({ code: "STALE_SOURCE" });
  }, 60_000);

  it("cascades all private source history and prevents in-flight work from resurrecting deleted projects", async () => {
    const repo = repository();
    const { scope, project } = await createOwnedProject(repo);
    const { args, request, impactHash } = await reviewedRequest(repo, scope, project);
    const draft = draftFor(request);
    const draftClaim = await repo.claimDraft({ ...args, draftId: draft.id, inputHash: hashRealInput(draft.style), sourceRevision: 1,
      reviewRevision: 1, impactHash, style: draft.style });
    const pending = requestFor(project);
    const pendingArgs = { scope, projectId: project.id, requestId: pending.id };
    const analysisClaim = await repo.claimRequest({ ...pendingArgs, inputHash: hashRealInput(pending.clientMessage), record: pending });
    if (!draftClaim.ownerToken || !analysisClaim.ownerToken) throw new Error("Synthetic claims need owners.");
    await expect(repo.deleteProject("not-this-session", project.id)).rejects.toMatchObject({ status: 404 });
    await repo.deleteProject(scope, project.id);
    await expect(repo.getProject(scope, project.id)).rejects.toMatchObject({ status: 404 });
    await expect(repo.getRequest(args)).rejects.toMatchObject({ status: 404 });
    await expect(repo.completeAnalysis({ ...pendingArgs, ownerToken: analysisClaim.ownerToken, analysis: analysisFor(pending) })).rejects.toMatchObject({ status: 404 });
    await expect(repo.completeDraft({ ...args, draftId: draft.id, ownerToken: draftClaim.ownerToken, draft })).rejects.toMatchObject({ status: 404 });
    // These exact synthetic IDs were generated and inserted by this test alone.
    const children = await pools[0].query(`SELECT
      (SELECT count(*)::int FROM scopeshift_real_requests WHERE project_id = $1) AS requests,
      (SELECT count(*)::int FROM scopeshift_real_drafts WHERE request_id = $2) AS drafts`, [project.id, request.id]);
    expect(children.rows).toEqual([{ requests: 0, drafts: 0 }]);
  }, 60_000);

  it("stores failed operation receipts without allowing pending retries to become new AI work", async () => {
    const repo = repository();
    const { scope, project, projectId } = await createOwnedProject(repo);
    const record = requestFor(project);
    const args = { scope, projectId, requestId: record.id, inputHash: hashRealInput(record.clientMessage), record };
    const claim = await repo.claimRequest(args);
    if (!claim.ownerToken) throw new Error("No synthetic analysis owner.");
    await expect(repo.completeAnalysis({ ...args, ownerToken: randomUUID(), analysis: analysisFor(record) })).rejects.toMatchObject({ code: "CONFLICT" });
    await repo.failAnalysis({ ...args, ownerToken: claim.ownerToken, error: { code: "AI_UNAVAILABLE", message: "Synthetic provider failure." } });
    await expect(repository().claimRequest(args)).resolves.toMatchObject({ created: false, ownerToken: null, request: { status: "failed", error: { code: "AI_UNAVAILABLE" } } });
    const reviewed = await reviewedRequest(repo, scope, project);
    const draft = draftFor(reviewed.request);
    const draftArgs = { ...reviewed.args, draftId: draft.id, inputHash: hashRealInput(draft.style), sourceRevision: 1,
      reviewRevision: 1, impactHash: reviewed.impactHash, style: draft.style };
    const draftClaim = await repo.claimDraft(draftArgs);
    if (!draftClaim.ownerToken) throw new Error("No synthetic draft owner.");
    await repo.failDraft({ ...draftArgs, ownerToken: draftClaim.ownerToken, error: { code: "AI_UNAVAILABLE", message: "Synthetic draft failure." } });
    await expect(repository().claimDraft(draftArgs)).resolves.toMatchObject({ created: false, ownerToken: null, status: "failed", draft: null, error: { code: "AI_UNAVAILABLE" } });
  }, 60_000);

  it("serializes draft completion with source edits and draft edits with review changes", async () => {
    const repo = repository();
    const { scope, project } = await createOwnedProject(repo);
    const { args, request, impactHash } = await reviewedRequest(repo, scope, project);
    const draft = draftFor(request);
    const claim = await repo.claimDraft({ ...args, draftId: draft.id, inputHash: hashRealInput(draft.style), sourceRevision: 1,
      reviewRevision: 1, impactHash, style: draft.style });
    if (!claim.ownerToken) throw new Error("No synthetic draft owner.");
    const locker = await pools[pools.length - 1].connect();
    const writer = await pools[pools.length - 1].connect();
    const lockedRepo = new PostgresRealProjectRepository(writer);
    let transaction = false;
    try {
      await writer.query("BEGIN");
      await writer.query("SET LOCAL lock_timeout = '150ms'");
      await locker.query("BEGIN"); transaction = true;
      await locker.query("SELECT id FROM scopeshift_real_projects WHERE id = $1 AND scope_hash = $2 FOR UPDATE", [project.id, realProjectScopeHash(scope)]);
      // This must wait for the source lock, even though its old MVCC image appears current.
      await expect(lockedRepo.completeDraft({ ...args, draftId: draft.id, ownerToken: claim.ownerToken, draft })).rejects.toMatchObject({ code: "STORAGE_UNAVAILABLE" });
      await writer.query("ROLLBACK");
      await locker.query("ROLLBACK"); transaction = false;
      await repo.completeDraft({ ...args, draftId: draft.id, ownerToken: claim.ownerToken, draft });
      await locker.query("BEGIN"); transaction = true;
      await locker.query(`SELECT r.id FROM scopeshift_real_requests r JOIN scopeshift_real_projects p ON p.id = r.project_id
        WHERE r.id = $1 AND p.id = $2 AND p.scope_hash = $3 FOR UPDATE OF r`, [request.id, project.id, realProjectScopeHash(scope)]);
      // Review invalidation holds this row. A draft edit must not bypass that lock.
      await writer.query("BEGIN");
      await writer.query("SET LOCAL lock_timeout = '150ms'");
      await expect(lockedRepo.editDraft({ ...args, draftId: draft.id, body: "Edited while review is locked." })).rejects.toMatchObject({ code: "STORAGE_UNAVAILABLE" });
      await writer.query("ROLLBACK");
      await locker.query("ROLLBACK"); transaction = false;
      await expect(repo.editDraft({ ...args, draftId: draft.id, body: "Edited after locks are released." })).resolves.toMatchObject({ body: "Edited after locks are released." });
    } finally {
      if (transaction) await locker.query("ROLLBACK");
      await writer.query("ROLLBACK");
      locker.release(); writer.release();
    }
  }, 60_000);

  it("enforces the ten-project limit under concurrent inserts without touching another session", async () => {
    const repo = repository();
    const scope = `real-repository-test-${randomUUID()}`;
    for (let count = 0; count < 9; count++) await createOwnedProject(repo, scope);
    const contenders = [buildRealProject(projectInput), buildRealProject(projectInput)];
    contenders.forEach((project) => owned.push({ scope, projectId: project.id }));
    const results = await Promise.allSettled(contenders.map((project) => repo.createProject(scope, project)));
    expect(results.filter((result) => result.status === "fulfilled")).toHaveLength(1);
    expect(results.filter((result) => result.status === "rejected").every((result) => result.status === "rejected" && result.reason.code === "LIMIT_REACHED")).toBe(true);
    expect(await repo.listProjects(scope)).toHaveLength(10);
  }, 60_000);
});
